    "of the harbour. For the first decade they sold coarse grey salt to fish-curers along the coast, carrying "
    "it in flat-bottomed boats that could cross the lagoon at low water. In 1924 a storm breached the outer "
    "dyke and flooded half of the evaporation pans with fresh water; three seasons of production were lost, "
    "and six of the founding families left for the city. The remaining members borrowed money from a grain "
    "merchant, rebuilt the dyke with stone instead of packed clay, and switched from grey salt to a finer white "
