# preregistered roles (see docs/V1_CORRECTNESS_CONTRACT.md)
ROLES = {
    "sentinel": ["english_prose_1", "turkish_prose_1", "python_code_1", "math_1"],
    "cache_invariance": ["json_1", "instruction_1"],
    "determinism_repeat": ["json_1", "math_1"],
    "multiseq": ["english_prose_2", "turkish_prose_2", "python_code_2", "json_2"],
    "api_ab": ["math_2", "instruction_2", "long_context_1", "english_prose_1"],
    "api_concurrency_1": ["math_2"],
    "api_concurrency_2": ["instruction_2", "turkish_prose_2"],
    "api_concurrency_4": ["english_prose_1", "python_code_1", "json_1", "long_context_2"],
    "api_stream": ["math_1"],
    "benchmark": ["math_1"],
}
UBATCH_LENGTHS = [511, 512, 513, 1100]
UBATCH_SEED = 20260919


def ubatch_passage(seed=UBATCH_SEED, n_sentences=260):
    rng = random.Random(seed)
    towns = ["Arlen", "Belcourt", "Corvid", "Dunmore", "Esker", "Falk", "Garrow", "Hollin", "Istra", "Jessup"]
    trades = ["weavers", "coopers", "tanners", "glassblowers", "millers", "ropemakers", "potters", "smiths"]
    goods = ["wool", "barrels", "leather", "lamps", "flour", "rope", "jugs", "nails", "salt", "honey"]
    out = []
    for i in range(n_sentences):
        out.append("In year %d the %s of %s sent %d loads of %s to %s, and the river was %s." % (
            1700 + rng.randrange(250), rng.choice(trades), rng.choice(towns), rng.randrange(2, 90),
            rng.choice(goods), rng.choice(towns), rng.choice(["high", "low", "frozen", "calm", "fast"])))
    return " ".join(out)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "prompts.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for pid, cat, text in PROMPTS:
            f.write(json.dumps({"id": pid, "text": text}, ensure_ascii=False) + "\n")

    # tokenize the passage with the pinned tokenizer (raw text, as run)
    tmp = os.path.join(OUT, "_tok")
    os.makedirs(tmp, exist_ok=True)
    passage = ubatch_passage()
    mf = os.path.join(tmp, "passage.jsonl")
    open(mf, "w", encoding="utf-8").write(json.dumps({"id": "passage", "text": passage, "raw": True}) + "\n")
    env = dict(os.environ, SABAH_DIAG_OUT=tmp, SABAH_DIAG_MANIFEST=mf, SABAH_DIAG_TOKENIZE_ONLY="1")
    subprocess.run([DIAG, "-m", MODEL, "-c", "4096", "-ngl", "0", "--cpu-moe"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    toks = np.fromfile(os.path.join(tmp, "passage", "prompt_tokens.i32"), np.int32).tolist()
    assert len(toks) > max(UBATCH_LENGTHS), len(toks)
    with open(os.path.join(OUT, "ubatch.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for n in UBATCH_LENGTHS:
            f.write(json.dumps({"id": "ubatch_%d" % n, "tokens": toks[:n]}) + "\n")

    manifest = dict(
        schema=1,
        note="v1 confirmatory corpus. Not used in RC4 or v1 development; frozen before any validation run.",
        prompts=[dict(id=pid, category=cat, sha256_utf8=sha(text.encode("utf-8")))
                 for pid, cat, text in PROMPTS],
        ubatch=[dict(id="ubatch_%d" % n, n_tokens=n,
                     sha256_token_ids=sha(np.asarray(toks[:n], np.int32).tobytes()))
                for n in UBATCH_LENGTHS],
        ubatch_source=dict(generator="tools/v1/make_corpus.py:ubatch_passage", seed=UBATCH_SEED,
                           passage_sha256_utf8=sha(passage.encode("utf-8")), passage_tokens=len(toks)),
        roles=ROLES,
        files={fn: sha(open(os.path.join(OUT, fn), "rb").read()) for fn in ("prompts.jsonl", "ubatch.jsonl")},
    )
    json.dump(manifest, open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print(json.dumps(manifest["files"], indent=1), len(toks), "passage tokens")


if __name__ == "__main__":
    main()
