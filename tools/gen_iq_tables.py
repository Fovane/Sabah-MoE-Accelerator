"""Extract ggml's IQ lookup tables into a self-contained C header.

Reads the qwen4exp-llama ggml-common.h and emits the tables Sabah needs, with
the element count checked against the source's declared size.
"""
import re
import sys

SRC = r"C:\Projects\qwen4exp-llama\ggml\src\ggml-common.h"
OUT = r"C:\Projects\quantization\Sabah-MoE-Accelerator\sabah\runtime\cuda\sabah_iq_tables.h"

WANT = [
    ("uint8_t",  "kmask_iq2xs",   8),
    ("uint8_t",  "ksigns_iq2xs",  128),
    ("uint64_t", "iq2s_grid",     1024),
    ("uint32_t", "iq3xxs_grid",   256),
    ("uint32_t", "iq3s_grid",     512),
    ("int8_t",   "kvalues_iq4nl", 16),
]

text = open(SRC, "r", encoding="utf-8", errors="replace").read()
lines = text.splitlines()

tables = {}
i = 0
while i < len(lines):
    m = re.match(r"\s*GGML_TABLE_BEGIN\((\w+),\s*(\w+),\s*(\w+)\)\s*$", lines[i])
    if m:
        typ, name, size = m.group(1), m.group(2), m.group(3)
        body = []
        i += 1
        while i < len(lines) and not lines[i].strip().startswith("GGML_TABLE_END"):
            body.append(lines[i])
            i += 1
        tables[name] = (typ, size, "\n".join(body))
    i += 1

out = []
out.append("// Generated by tools/gen_iq_tables.py from ggml-common.h - do not edit.")
out.append("// Lookup tables for the IQ-family expert quants (IQ2_S, IQ3_S, IQ3_XXS,")
out.append("// IQ4_NL, IQ4_XS).")
out.append("//")
out.append("// Two copies of every table are emitted on purpose: `<name>` is a plain")
out.append("// host array (used by the host reference dequantizer) and `<name>_dev`")
out.append("// is the device-visible twin used by the sub32_* kernels. A single")
out.append("// `static const` array cannot serve both: nvcc refuses to touch a host")
out.append("// array from device code, and the host cannot read a __device__ one.")
out.append("#pragma once")
out.append("")
out.append("#include <cstdint>")
out.append("")
out.append("#if defined(__CUDACC__)")
out.append("#define SABAH_DEV_TABLE __device__")
out.append("#else")
# A host-only compiler (icx, clangd, static analysis) still has to parse this
# header, so the device twin must degrade to something legal rather than vanish:
# nothing on the host path references it.
out.append("#define SABAH_DEV_TABLE")
out.append("#endif")
out.append("")

ok = True
for typ, name, size in WANT:
    if name not in tables:
        print("MISSING table:", name)
        ok = False
        continue
    got_typ, got_size, body = tables[name]
    if got_typ != typ or int(got_size) != size:
        print("SIZE MISMATCH", name, got_typ, got_size, "expected", typ, size)
        ok = False
        continue
    # element count: strip line comments, then count comma-separated tokens
    code = "\n".join(re.sub(r"//.*$", "", ln) for ln in body.splitlines())
    n_elems = len([t for t in code.split(",") if t.strip()])
    if n_elems != size:
        print("ELEMENT COUNT MISMATCH", name, n_elems, "expected", size)
        ok = False
        continue
    out.append("static const %s %s[%d] = {" % (typ, name, size))
    out.append(body)
    out.append("};")
    out.append("")
    out.append("static const SABAH_DEV_TABLE %s %s_dev[%d] = {" % (typ, name, size))
    out.append(body)
    out.append("};")
    out.append("")

if not ok:
    sys.exit("table extraction failed")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote", OUT)
for typ, name, size in WANT:
    print("  %-14s %-10s %d elements" % (name, typ, size))
